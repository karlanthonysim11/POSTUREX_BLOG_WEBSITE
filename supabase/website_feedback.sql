-- Visitor star ratings for the POSTUREX showcase website.
-- Run once in the Supabase SQL Editor. Safe to run again.
--
-- Anyone can submit a rating (1–5) with an optional name and comment.
-- Visitors only see approved rows. New rows are approved by default;
-- to hide a review, set its "approved" column to false in the Table Editor.

create table if not exists public.website_feedback (
  id bigint generated by default as identity primary key,
  name text check (name is null or char_length(name) between 1 and 60),
  rating smallint not null check (rating between 1 and 5),
  comment text check (comment is null or char_length(comment) <= 500),
  approved boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists website_feedback_approved_created_idx
  on public.website_feedback (approved, created_at desc);

alter table public.website_feedback enable row level security;

drop policy if exists "Anyone can submit website feedback" on public.website_feedback;
create policy "Anyone can submit website feedback"
on public.website_feedback
for insert
to anon, authenticated
with check (approved = true);

drop policy if exists "Anyone can read approved website feedback" on public.website_feedback;
create policy "Anyone can read approved website feedback"
on public.website_feedback
for select
to anon, authenticated
using (approved = true);

-- Visitors may only set these three columns; id, approved and created_at use defaults.
revoke all on public.website_feedback from anon, authenticated;
grant insert (name, rating, comment) on public.website_feedback to anon, authenticated;
grant select (id, name, rating, comment, approved, created_at) on public.website_feedback to anon, authenticated;
grant usage, select on sequence public.website_feedback_id_seq to anon, authenticated;

-- Average and star distribution over approved ratings.
create or replace function public.website_feedback_summary()
returns json
language sql
stable
security invoker
set search_path = public
as $$
  select json_build_object(
    'count',   count(*),
    'average', coalesce(round(avg(rating)::numeric, 2), 0),
    'd5', count(*) filter (where rating = 5),
    'd4', count(*) filter (where rating = 4),
    'd3', count(*) filter (where rating = 3),
    'd2', count(*) filter (where rating = 2),
    'd1', count(*) filter (where rating = 1)
  )
  from public.website_feedback
  where approved;
$$;

grant execute on function public.website_feedback_summary() to anon, authenticated;
